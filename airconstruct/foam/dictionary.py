"""Minimal OpenFOAM dictionary serializer (shared by every module writing case files).

Python -> OpenFOAM mapping:
  dict            -> { key value; ... }   (nested sub-dictionaries)
  list / tuple    -> ( a b c )
  bool            -> true / false
  int / float     -> number
  str             -> written verbatim (so "uniform (0 0 0)" or "$internalField" work)
  Raw(text)       -> verbatim text, used for directives such as "#include"
A key whose value is None is written as a bare keyword line ("key;" is not emitted).
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

HEADER = """/*--------------------------------*- C++ -*----------------------------------*\\
  Generated by Air-Construct. Edits may be overwritten.
\\*---------------------------------------------------------------------------*/
FoamFile
{{
    version     2.0;
    format      ascii;
    class       {cls};
    location    "{location}";
    object      {obj};
}}
"""


class Raw(str):
    """Text emitted as-is inside a dictionary."""


def fmt_value(v: Any, indent: int = 0) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v) if isinstance(v, float) else str(v)
    if isinstance(v, (list, tuple)):
        return "(" + " ".join(fmt_value(x, indent) for x in v) + ")"
    if isinstance(v, dict):
        pad = "    " * indent
        return "\n" + pad + "{\n" + fmt_entries(v, indent + 1) + pad + "}"
    return str(v)


def fmt_entries(d: dict, indent: int = 0) -> str:
    pad = "    " * indent
    out = []
    for k, v in d.items():
        if isinstance(v, Raw):
            out.append(f"{pad}{v}\n")
        elif isinstance(v, dict):
            out.append(f"{pad}{_key(k)}{fmt_value(v, indent)}\n")
        elif v is None:
            out.append(f"{pad}{_key(k)};\n")
        else:
            out.append(f"{pad}{_key(k):<15} {fmt_value(v, indent)};\n")
    return "".join(out)


def _key(k: str) -> str:
    # regex keys (e.g. ".*_to_.*") must be quoted
    if any(ch in k for ch in "*|()[]^$+?"):
        return f'"{k}"'
    return k


def write_foam_dict(
    path: Path, body: dict, cls: str = "dictionary", obj: str | None = None, extra: str = ""
) -> Path:
    """Write ``body`` as an OpenFOAM file at ``path`` (parents created)."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    location = path.parent.name
    text = HEADER.format(cls=cls, location=location, obj=obj or path.name)
    text += "\n" + fmt_entries(body) + extra
    path.write_text(text)
    return path
