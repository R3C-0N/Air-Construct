"""OpenFOAM function objects that report live numbers in the solver log.

Owned by: workstream "results" (live monitoring). Written by the runner to
system/monitors, which the generated controlDict includes in its ``functions``
dictionary (``#includeIfPresent "monitors"``).

Every object logs to stdout (``log true``), so :class:`airconstruct.monitor.RunMonitor`
reads the numbers from the solver output as it runs:

- ``T_<region>``: volume average temperature of every region (min and max come from
  the solver's own "Min/max T" lines);
- ``heat_air``: wall heat flux integrated over every air wall patch (one per component
  interface ``air_to_<part>`` plus the enclosure walls), positive into the air;
- ``flow_<opening>``, ``T_<opening>``, ``p_<opening>``: mass flow (sum of phi), flux
  weighted temperature and area mean p_rgh of every opening.
"""

from __future__ import annotations

from pathlib import Path

from ..case import Case
from .dictionary import fmt_entries

LIBS = "(fieldFunctionObjects)"


def _common(region: str) -> dict:
    return {"libs": LIBS, "region": region, "writeControl": "timeStep", "writeInterval": 1,
            "writeFields": False, "log": True}


def monitor_objects(case: Case) -> dict:
    """{name: function object dict} for the live monitors of `case`."""
    air = case.fluid_region
    out: dict[str, dict] = {}
    for region in [air] + case.solid_regions:
        out[f"T_{region}"] = {"type": "volFieldValue", **_common(region),
                              "regionType": "all", "operation": "volAverage", "fields": "(T)"}
    out["heat_air"] = {"type": "wallHeatFlux", **_common(air)}
    for o in case.openings:
        patch = {"type": "surfaceFieldValue", **_common(air), "regionType": "patch",
                 "name": o.name, "surfaceFormat": "none"}
        out[f"flow_{o.name}"] = {**patch, "operation": "sum", "fields": "(phi)"}
        out[f"T_{o.name}"] = {**patch, "operation": "weightedAverage", "weightField": "phi",
                              "fields": "(T)"}
        out[f"p_{o.name}"] = {**patch, "operation": "areaAverage", "fields": "(p_rgh)"}
    return out


def write_monitors(case: Case, case_dir: Path, enabled: bool = True) -> Path:
    """Write system/monitors (empty when not enabled, so the include stays valid).

    Plain entries, no FoamFile header: the file is included inside the controlDict's
    ``functions`` dictionary, where a header would read as one more function object."""
    path = Path(case_dir) / "system" / "monitors"
    path.parent.mkdir(parents=True, exist_ok=True)
    body = fmt_entries(monitor_objects(case)) if enabled else ""
    path.write_text("// Live monitors, generated by Air-Construct (foam/monitors.py)\n" + body)
    return path
